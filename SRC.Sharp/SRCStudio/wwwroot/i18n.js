function detect() {
  const param = new URLSearchParams(globalThis.location?.search ?? '').get('lang');
  const lang = (param || globalThis.document?.documentElement?.lang || globalThis.navigator?.language || 'ja').toLowerCase();
  return lang.startsWith('ja') ? 'ja' : 'en';
}

export const language = detect();

/** 文字列。{0}・{1} を args で置き換える */
export function t(key, ...args) {
  const s = strings[language][key] ?? strings.ja[key] ?? key;
  return s.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)]));
}
